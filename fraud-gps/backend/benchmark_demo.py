"""Measure isolated loopback HTTP first-use and warm latency; never modifies data."""

import argparse
import json
import os
import platform
import socket
import statistics
import subprocess
import sys
import tempfile
import time
import urllib.request
from decimal import Decimal
from pathlib import Path

from demo_process import stop_demo_process

ROOT = Path(__file__).resolve().parent


def request(base, path, body=None):
    payload = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(base + path, payload, {"Content-Type": "application/json"})
    start = time.perf_counter()
    with urllib.request.urlopen(req, timeout=60) as response:
        content = response.read()
    return (time.perf_counter() - start) * 1000, content


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--samples", type=int, default=7)
    parser.add_argument("--data-dir", type=Path)
    args = parser.parse_args()
    if args.samples < 3:
        parser.error("At least three warm samples are required")
    with socket.socket() as probe:
        probe.bind(("127.0.0.1", 0))
        port = probe.getsockname()[1]
    base = f"http://127.0.0.1:{port}"
    environment = dict(os.environ)
    if args.data_dir:
        environment["FRAUD_GPS_DATA_DIR"] = str(args.data_dir.resolve())
    with tempfile.TemporaryFile() as log:
        startup = time.perf_counter()
        process = subprocess.Popen(
            [
                sys.executable,
                "-m",
                "uvicorn",
                "app.main:app",
                "--host",
                "127.0.0.1",
                "--port",
                str(port),
            ],
            cwd=ROOT,
            env=environment,
            stdout=log,
            stderr=log,
        )
        try:
            deadline = time.perf_counter() + 60
            while True:
                try:
                    _, raw = request(base, "/health")
                    health = json.loads(raw)
                    break
                except OSError:
                    if process.poll() is not None or time.perf_counter() > deadline:
                        log.seek(0)
                        raise RuntimeError(log.read().decode(errors="replace")) from None
                    time.sleep(0.1)
            startup_ms = (time.perf_counter() - startup) * 1000
            _, raw = request(base, "/api/complaints?limit=200")
            cases = json.loads(raw)["items"]
            case = max(cases, key=lambda item: Decimal(item["amount_lost"]))
            cid = case["complaint_id"]
            aid = case["suspect_account"]
            options = {"max_depth": 5, "min_amount": "100", "forwarding_window_hours": 24}
            query = "?max_depth=5&min_amount=100&forwarding_window_hours=24"
            endpoints = [
                ("graph_full", "/api/graph/full", None),
                ("risk", f"/api/risk/{aid}", None),
                ("trace", "/api/trace", {"complaint_id": cid, **options}),
                ("trail_graph", f"/api/graph/trail/{cid}{query}", None),
                ("timeline", f"/api/timeline/{cid}{query}", None),
                ("dna", f"/api/dna/{cid}{query}", None),
                ("summary", f"/api/report/{cid}/summary{query}", None),
                ("pdf", f"/api/report/{cid}", options),
            ]
            results = {}
            for name, path, body in endpoints:
                first, raw = request(base, path, body)
                timings = [request(base, path, body)[0] for _ in range(args.samples)]
                results[name] = {
                    "first_ms": round(first, 2),
                    "warm_median_ms": round(statistics.median(timings), 2),
                    "warm_max_ms": round(max(timings), 2),
                    "warm_samples_ms": [round(t, 2) for t in timings],
                    "response_bytes": len(raw),
                    "target_ms": 500,
                    "passed": max(first, *timings) < 500,
                }
            result = {
                "environment": {
                    "os": platform.platform(),
                    "python": platform.python_version(),
                    "cpu": platform.processor(),
                },
                "conditions": (
                    "Fresh isolated server; startup excluded from request timing; "
                    "ordered first-use "
                    "then warm samples. HTTP serialization and loopback transfer included. "
                    "No concurrent requests generated by the benchmark."
                ),
                "startup_ms": round(startup_ms, 2),
                "base_url": base,
                "dataset": health,
                "case_id": cid,
                "options": options,
                "results": results,
            }
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
            print(
                json.dumps(
                    {
                        "output": str(args.output),
                        "startup_ms": result["startup_ms"],
                        "results": results,
                    },
                    indent=2,
                )
            )
            if not all(result["passed"] for result in results.values()):
                sys.exit(1)
        finally:
            stop_demo_process(process)


if __name__ == "__main__":
    main()
